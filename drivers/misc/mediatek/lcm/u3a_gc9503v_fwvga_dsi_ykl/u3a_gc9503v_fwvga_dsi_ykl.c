static void lcm_init(void)
{
#ifndef BUILD_LK
	mt6357_upmu_set_rg_ldo_vldo28_en(1);
	mt6357_upmu_set_rg_ldo_vldo28_1_en(1);
	mt6357_upmu_set_rg_ldo_vldo28_sw_op_en(1);
#endif
	MDELAY(100);
	SET_RESET_PIN(1);
	MDELAY(10);
	SET_RESET_PIN(0);
	MDELAY(10);
	SET_RESET_PIN(1);
	MDELAY(120);

	push_table(lcm_init_setting, ARY_SIZE(lcm_init_setting));

	LCM_LOGI("[LLF_kernel]:u3a_infinish\n");
}

